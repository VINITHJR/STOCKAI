"""
Phase 12 - Layer 7: Risk Alerts

Converts risk evaluations and position conditions into
structured RiskAlert objects.

This layer does not calculate risk.
It consumes the outputs of previous Phase 12 layers.

No database or external notification system is used.
Alerts are maintained in memory.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from uuid import uuid4

from .models import (
    RiskAlert,
    RiskEvaluation,
    RiskStatus,
    RiskLevel,
    RiskType,
)


class RiskAlertManager:
    """
    Phase 12 - Layer 7

    Generates and manages risk alerts from RiskEvaluation
    objects and position-level trigger conditions.
    """

    def __init__(self) -> None:
        self.alerts: List[RiskAlert] = []

    # ==========================================================
    # ALERT CREATION
    # ==========================================================

    def create_alert(
        self,
        risk_type: RiskType,
        level: RiskLevel,
        status: RiskStatus,
        message: str,
        instrument_key: Optional[str] = None,
        current_value: Optional[float] = None,
        limit_value: Optional[float] = None,
    ) -> RiskAlert:
        """
        Create and store a RiskAlert using the existing
        RiskAlert model.
        """

        alert = RiskAlert(
            alert_id=str(uuid4()),
            risk_type=risk_type,
            level=level,
            status=status,
            message=message,
            instrument_key=instrument_key,
            current_value=current_value,
            limit_value=limit_value,
        )

        self.alerts.append(alert)

        return alert

    # ==========================================================
    # RISK EVALUATION -> ALERT
    # ==========================================================

    def alert_from_evaluation(
        self,
        evaluation: RiskEvaluation,
        risk_type: Optional[RiskType] = None,
        instrument_key: Optional[str] = None,
    ) -> Optional[RiskAlert]:
        """
        Convert a RiskEvaluation into a RiskAlert.

        SAFE evaluations do not create alerts.

        WARNING and BLOCKED evaluations create alerts.

        Existing message/current_value/limit_value fields from
        RiskEvaluation are preserved whenever available.
        """

        if evaluation.status == RiskStatus.SAFE:
            return None

        alert_risk_type = (
            risk_type
            or evaluation.risk_type
            or RiskType.POSITION_SIZE
        )

        alert_instrument_key = (
            instrument_key
            if instrument_key is not None
            else evaluation.instrument_key
        )

        # Prefer the message generated by RiskEngine.
        message = evaluation.message

        # If the evaluation did not provide a message,
        # construct a fallback message.
        if not message:
            if evaluation.status == RiskStatus.WARNING:
                message = (
                    f"{alert_risk_type.value} warning: "
                    f"current value "
                    f"{evaluation.current_value:.2f} "
                    f"is approaching the limit of "
                    f"{evaluation.limit_value:.2f}."
                )
            else:
                message = (
                    f"{alert_risk_type.value} limit breached: "
                    f"current value "
                    f"{evaluation.current_value:.2f} "
                    f"exceeds the limit of "
                    f"{evaluation.limit_value:.2f}."
                )

        return self.create_alert(
            risk_type=alert_risk_type,
            level=evaluation.level,
            status=evaluation.status,
            message=message,
            instrument_key=alert_instrument_key,
            current_value=evaluation.current_value,
            limit_value=evaluation.limit_value,
        )

    # ==========================================================
    # POSITION SIZE
    # ==========================================================

    def check_position_size(
        self,
        evaluation: RiskEvaluation,
        instrument_key: Optional[str] = None,
    ) -> Optional[RiskAlert]:
        """
        Generate a position-size alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.POSITION_SIZE,
            instrument_key=instrument_key,
        )

    # ==========================================================
    # POSITION EXPOSURE
    # ==========================================================

    def check_position_exposure(
        self,
        evaluation: RiskEvaluation,
        instrument_key: Optional[str] = None,
    ) -> Optional[RiskAlert]:
        """
        Generate a position-exposure alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.POSITION_EXPOSURE,
            instrument_key=instrument_key,
        )

    # ==========================================================
    # PORTFOLIO EXPOSURE
    # ==========================================================

    def check_portfolio_exposure(
        self,
        evaluation: RiskEvaluation,
    ) -> Optional[RiskAlert]:
        """
        Generate a portfolio-exposure alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.PORTFOLIO_EXPOSURE,
        )

    # ==========================================================
    # DRAWDOWN
    # ==========================================================

    def check_drawdown(
        self,
        evaluation: RiskEvaluation,
    ) -> Optional[RiskAlert]:
        """
        Generate a drawdown alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.DRAWDOWN,
        )

    # ==========================================================
    # DAILY LOSS
    # ==========================================================

    def check_daily_loss(
        self,
        evaluation: RiskEvaluation,
    ) -> Optional[RiskAlert]:
        """
        Generate a daily-loss alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.LOSS_LIMIT,
        )

    # ==========================================================
    # CAPITAL
    # ==========================================================

    def check_capital(
        self,
        evaluation: RiskEvaluation,
    ) -> Optional[RiskAlert]:
        """
        Generate a capital-availability alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.CAPITAL,
        )

    # ==========================================================
    # CONCENTRATION
    # ==========================================================

    def check_concentration(
        self,
        evaluation: RiskEvaluation,
        instrument_key: Optional[str] = None,
    ) -> Optional[RiskAlert]:
        """
        Generate a concentration-risk alert.
        """

        return self.alert_from_evaluation(
            evaluation=evaluation,
            risk_type=RiskType.CONCENTRATION,
            instrument_key=instrument_key,
        )

    # ==========================================================
    # STOP LOSS
    # ==========================================================

    def check_stop_loss(
        self,
        triggered: bool,
        instrument_key: str,
        current_price: float,
        stop_loss_price: float,
    ) -> Optional[RiskAlert]:
        """
        Generate a stop-loss alert when the stop-loss is triggered.
        """

        if not triggered:
            return None

        return self.create_alert(
            risk_type=RiskType.STOP_LOSS,
            level=RiskLevel.HIGH,
            status=RiskStatus.BLOCKED,
            message=(
                f"Stop-loss triggered for {instrument_key}: "
                f"current price {current_price:.2f} "
                f"reached stop-loss price "
                f"{stop_loss_price:.2f}."
            ),
            instrument_key=instrument_key,
            current_value=current_price,
            limit_value=stop_loss_price,
        )

    # ==========================================================
    # TAKE PROFIT
    # ==========================================================

    def check_take_profit(
        self,
        triggered: bool,
        instrument_key: str,
        current_price: float,
        take_profit_price: float,
    ) -> Optional[RiskAlert]:
        """
        Generate an alert when the take-profit target is reached.

        RiskType does not contain a separate TAKE_PROFIT enum in
        the existing Phase 12 model, so this is represented using
        the existing STOP_LOSS risk type for compatibility with
        the current model schema.
        """

        if not triggered:
            return None

        return self.create_alert(
            risk_type=RiskType.STOP_LOSS,
            level=RiskLevel.LOW,
            status=RiskStatus.WARNING,
            message=(
                f"Take-profit target reached for {instrument_key}: "
                f"current price {current_price:.2f} "
                f"reached target price "
                f"{take_profit_price:.2f}."
            ),
            instrument_key=instrument_key,
            current_value=current_price,
            limit_value=take_profit_price,
        )

    # ==========================================================
    # MULTIPLE EVALUATIONS
    # ==========================================================

    def evaluate_all(
        self,
        evaluations: Dict[RiskType, RiskEvaluation],
    ) -> List[RiskAlert]:
        """
        Convert multiple RiskEvaluation objects into alerts.

        SAFE evaluations are ignored.
        """

        generated: List[RiskAlert] = []

        for risk_type, evaluation in evaluations.items():

            alert = self.alert_from_evaluation(
                evaluation=evaluation,
                risk_type=risk_type,
            )

            if alert is not None:
                generated.append(alert)

        return generated

    # ==========================================================
    # ALERT RETRIEVAL
    # ==========================================================

    def get_alerts(self) -> List[RiskAlert]:
        """
        Return all generated alerts.
        """

        return list(self.alerts)

    def get_active_alerts(self) -> List[RiskAlert]:
        """
        Return unacknowledged WARNING/BLOCKED alerts.
        """

        return [
            alert
            for alert in self.alerts
            if (
                alert.status != RiskStatus.SAFE
                and not alert.acknowledged
            )
        ]

    # ==========================================================
    # ACKNOWLEDGE ALERT
    # ==========================================================

    def acknowledge_alert(
        self,
        alert_id: str,
    ) -> Optional[RiskAlert]:
        """
        Mark an alert as acknowledged.

        Returns the updated alert or None if the alert does not
        exist.
        """

        for alert in self.alerts:

            if alert.alert_id == alert_id:
                alert.acknowledged = True
                return alert

        return None

    # ==========================================================
    # CLEAR ALERTS
    # ==========================================================

    def clear_alerts(self) -> None:
        """
        Clear all in-memory alerts.
        """

        self.alerts.clear()

    # ==========================================================
    # COUNTS
    # ==========================================================

    def get_alert_count(self) -> int:
        """
        Return total generated alert count.
        """

        return len(self.alerts)

    def get_active_alert_count(self) -> int:
        """
        Return count of active unacknowledged alerts.
        """

        return len(self.get_active_alerts())

    # ==========================================================
    # SUMMARY
    # ==========================================================

    def summary(self) -> Dict[str, Any]:
        """
        Return a structured summary of active alerts.
        """

        active_alerts = self.get_active_alerts()

        warning_count = sum(
            1
            for alert in active_alerts
            if alert.status == RiskStatus.WARNING
        )

        blocked_count = sum(
            1
            for alert in active_alerts
            if alert.status == RiskStatus.BLOCKED
        )

        critical_count = sum(
            1
            for alert in active_alerts
            if alert.level == RiskLevel.CRITICAL
        )

        high_count = sum(
            1
            for alert in active_alerts
            if alert.level == RiskLevel.HIGH
        )

        return {
            "total_alerts": len(active_alerts),
            "warning_alerts": warning_count,
            "blocked_alerts": blocked_count,
            "critical_alerts": critical_count,
            "high_alerts": high_count,
            "has_critical_risk": critical_count > 0,
        }


# ==============================================================
# BACKWARD-COMPATIBLE ALIAS
# ==============================================================

RiskAlerts = RiskAlertManager