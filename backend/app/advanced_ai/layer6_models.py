from typing import List
from pydantic import BaseModel, Field


# ============================================================
# PHASE 14 — LAYER 6
# ADVANCED AI VALIDATION
# ============================================================


class AIValidationInput(BaseModel):
    """
    Input for Phase 14 Layer 6.

    Layer 6 validates the consistency and quality of the
    recommendation produced by Layer 5 against the intelligence
    generated by Layers 1–4.
    """

    # --------------------------------------------------------
    # Instrument
    # --------------------------------------------------------
    instrument_key: str

    # --------------------------------------------------------
    # Layer 1 — AI Decision
    # --------------------------------------------------------
    ai_decision: str
    ai_confidence: float = Field(
        ge=0.0,
        le=1.0
    )

    # --------------------------------------------------------
    # Layer 2 — Reliability
    # --------------------------------------------------------
    reliability_score: float = Field(
        ge=0.0,
        le=1.0
    )

    confidence_grade: str = "E"
    confidence_band: str = "VERY_LOW"
    reliability_level: str = "VERY_LOW"
    decision_strength: str = "WEAK"
    risk_level: str = "HIGH"

    model_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    market_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    signal_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    supporting_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    # --------------------------------------------------------
    # Model Agreement / Conflict
    # --------------------------------------------------------
    model_count: int = Field(
        default=0,
        ge=0
    )

    agreement_count: int = Field(
        default=0,
        ge=0
    )

    conflict: bool = False
    conflict_level: str = "none"

    # --------------------------------------------------------
    # Layer 4 — Market Context
    # --------------------------------------------------------
    market_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    sector_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    overall_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    market_alignment: str = "NEUTRAL"
    sector_alignment: str = "NEUTRAL"
    overall_alignment: str = "NEUTRAL"

    context_strength: str = "WEAK"
    context_risk: str = "MEDIUM"
    overall_context: str = "NEUTRAL"

    # --------------------------------------------------------
    # Layer 5 — Recommendation
    # --------------------------------------------------------
    recommendation: str
    recommendation_confidence: float = Field(
        ge=0.0,
        le=1.0
    )

    recommendation_quality: str = "UNCERTAIN"
    recommendation_strength: str = "WEAK"

    recommendation_risk: str = "HIGH"

    recommendation_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    bullish_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    bearish_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    neutral_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )


class AIValidationResult(BaseModel):
    """
    Output produced by Phase 14 Layer 6.
    """

    # --------------------------------------------------------
    # Instrument
    # --------------------------------------------------------
    instrument_key: str

    # --------------------------------------------------------
    # Recommendation
    # --------------------------------------------------------
    recommendation: str
    recommendation_confidence: float

    # --------------------------------------------------------
    # Validation
    # --------------------------------------------------------
    validation_status: str
    validation_score: float
    validation_quality: str

    # --------------------------------------------------------
    # Individual Checks
    # --------------------------------------------------------
    decision_consistency: bool
    confidence_consistency: bool
    reliability_consistency: bool
    context_consistency: bool
    risk_consistency: bool
    conflict_consistency: bool

    # --------------------------------------------------------
    # Validation Details
    # --------------------------------------------------------
    passed_checks: List[str] = Field(
        default_factory=list
    )

    failed_checks: List[str] = Field(
        default_factory=list
    )

    warnings: List[str] = Field(
        default_factory=list
    )

    # --------------------------------------------------------
    # Risk
    # --------------------------------------------------------
    validation_risk: str

    # --------------------------------------------------------
    # Recommendation Assessment
    # --------------------------------------------------------
    recommendation_valid: bool
    recommendation_trust: str

    # --------------------------------------------------------
    # Source Metrics
    # --------------------------------------------------------
    ai_decision: str
    ai_confidence: float
    reliability_score: float
    overall_context_score: float
    recommendation_risk: str

    # --------------------------------------------------------
    # Status
    # --------------------------------------------------------
    status: str = "success"