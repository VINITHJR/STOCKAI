from typing import List
from pydantic import BaseModel, Field


# ============================================================
# PHASE 14 — LAYER 5
# AI RECOMMENDATION ENGINE
# ============================================================


class AIRecommendationInput(BaseModel):
    """
    Input for Phase 14 Layer 5.

    Layer 5 consumes the intelligence generated by the
    previous layers and converts it into an actionable
    recommendation.

    Layer 5 does not directly execute trades.
    """

    # --------------------------------------------------------
    # Instrument
    # --------------------------------------------------------
    instrument_key: str

    # --------------------------------------------------------
    # Layer 1 — AI Decision
    # --------------------------------------------------------
    decision: str
    decision_confidence: float = Field(
        ge=0.0,
        le=1.0
    )

    # --------------------------------------------------------
    # Layer 2 — Confidence & Reliability
    # --------------------------------------------------------
    reliability_score: float = Field(
        ge=0.0,
        le=1.0
    )

    confidence_grade: str = "E"
    confidence_band: str = "VERY_LOW"
    reliability_level: str = "VERY_LOW"
    recommendation_quality: str = "UNCERTAIN"
    decision_strength: str = "WEAK"
    risk_level: str = "HIGH"

    model_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    market_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    signal_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    supporting_reliability: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    # --------------------------------------------------------
    # Layer 2 — Model Context
    # --------------------------------------------------------

    model_count: int = Field(
        default=0,
        ge=0
    )

    agreement_count: int = Field(
        default=0,
        ge=0
    )

    # Directional agreement is separate from neutral agreement.
    # None preserves compatibility with older callers.
    directional_agreement_count: int | None = Field(
        default=None,
        ge=0,
    )


    # Phase 9 ensemble direction is needed to distinguish neutral consensus
    # from bullish/bearish directional confirmation.
    ensemble_signal: str = "neutral"

    conflict: bool = False
    conflict_level: str = "none"
    directional_conflict: bool = False
    disagreement_type: str = "none"
    agreement_type: str = "no_directional_consensus"
    neutral_agreement_count: int = Field(default=0, ge=0)

    # --------------------------------------------------------
    # Layer 3 — Explainability
    # --------------------------------------------------------
    strongest_factor: str = ""
    strongest_risk: str = ""

    bullish_factors: List[str] = Field(
        default_factory=list
    )

    bearish_factors: List[str] = Field(
        default_factory=list
    )

    neutral_factors: List[str] = Field(
        default_factory=list
    )

    supporting_factors: List[str] = Field(
        default_factory=list
    )

    conflicting_factors: List[str] = Field(
        default_factory=list
    )

    explanation_risk_factors: List[str] = Field(
        default_factory=list
    )

    # --------------------------------------------------------
    # Layer 4 — Market Context
    # --------------------------------------------------------
    market_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    sector_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    overall_context_score: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0
    )

    market_alignment: str = "NEUTRAL"
    sector_alignment: str = "NEUTRAL"
    overall_alignment: str = "NEUTRAL"

    context_strength: str = "WEAK"
    context_risk: str = "MEDIUM"
    overall_context: str = "NEUTRAL"

    market_regime: str = "unknown"
    market_direction: str = "neutral"
    market_confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )

    sector: str = "Unknown"
    sector_direction: str = "neutral"
    sector_confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )


class AIRecommendationResult(BaseModel):
    """
    Output produced by Phase 14 Layer 5.
    """

    # --------------------------------------------------------
    # Instrument
    # --------------------------------------------------------
    instrument_key: str

    # --------------------------------------------------------
    # Original AI Decision
    # --------------------------------------------------------
    ai_decision: str
    ai_confidence: float

    # --------------------------------------------------------
    # Final Recommendation
    # --------------------------------------------------------
    recommendation: str
    recommendation_confidence: float

    # --------------------------------------------------------
    # Recommendation Quality
    # --------------------------------------------------------
    recommendation_quality: str
    recommendation_strength: str

    # --------------------------------------------------------
    # Risk
    # --------------------------------------------------------
    risk_level: str
    recommendation_risk: str

    # --------------------------------------------------------
    # Context
    # --------------------------------------------------------
    market_context: str
    market_alignment: str
    sector_alignment: str
    overall_alignment: str

    # --------------------------------------------------------
    # Supporting Evidence
    # --------------------------------------------------------
    recommendation_score: float
    bullish_score: float
    bearish_score: float
    neutral_score: float

    # --------------------------------------------------------
    # Recommendation Factors
    # --------------------------------------------------------
    supporting_factors: List[str] = Field(
        default_factory=list
    )

    conflicting_factors: List[str] = Field(
        default_factory=list
    )

    warnings: List[str] = Field(
        default_factory=list
    )

    # --------------------------------------------------------
    # Guidance
    # --------------------------------------------------------
    action_guidance: str
    position_guidance: str

    # --------------------------------------------------------
    # Strongest Evidence
    # --------------------------------------------------------
    strongest_factor: str
    strongest_risk: str

    # --------------------------------------------------------
    # Source Metrics
    # --------------------------------------------------------
    reliability_score: float
    overall_context_score: float

    # --------------------------------------------------------
    # Status
    # --------------------------------------------------------
    # Additive agreement diagnostics; legacy response fields remain intact.
    model_count: int = Field(default=0, ge=0)
    agreement_count: int = Field(default=0, ge=0)
    directional_agreement_count: int = Field(default=0, ge=0)
    neutral_agreement_count: int = Field(default=0, ge=0)
    agreement_type: str = "no_directional_consensus"
    conflict: bool = False
    conflict_level: str = "none"
    directional_conflict: bool = False
    disagreement_type: str = "none"

    status: str = "success"
